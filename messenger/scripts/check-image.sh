#!/bin/bash
# Проверки собранного образа мессенджера: сжатый размер меньше порога, пользователь
# 65532:65532 (nonroot из distroless), команда version отвечает версией из --build-arg.
# Один скрипт для двух мест запуска: npm run check:images локально и джоба image в CI.
#
# Запуск из каталога messenger:
#   scripts/check-image.sh <образ> <ожидаемая версия>
set -euo pipefail

if [ $# -ne 2 ]; then
	echo "использование: scripts/check-image.sh <образ> <ожидаемая версия>" >&2
	exit 2
fi
image=$1
want_version=$2

# Порог из спеки (§11): distroless static + статический бинарь мессенджера. Меряем
# сжатый размер — столько качается из реестра — и меряем сами, а не берём {{.Size}}:
# его смысл зависит от хранилища образов и даже от версии Docker:
# - overlay2 / graphdriver (возможен на раннере CI) — распакованные слои;
# - containerd image store на Docker 29.9.1 — место на диске: распакованные слои плюс
#   сжатые архивы (25,6 МБ у образа после 2a при сжатом 6,0 МБ), хотя в более ранних
#   версиях 29.x тот же запрос давал сжатый размер (3,84 МБ у образа урока 1.16).
# `docker save | gzip` на containerd отдаёт уже сжатые архивы слоёв, и повторный gzip
# почти ничего не меняет: 3 832 236 байт против 3,84 МБ в реестре. На overlay2 save
# отдаёт распакованные слои, и gzip должен сжать их примерно до того же — но это
# рассуждение, а не замер: на overlay2 его не делали. Размер печатается, и первый прогон
# CI покажет, совпадает ли он. Сумма size слоёв из манифеста была бы точнее, но на
# overlay2 сжатых слоёв нет, пока образ не отправлен в реестр.
# Замер (Docker 29.9.1, containerd): образ тега m01-l16 — 3 832 236 байт, после 2a
# (pgx и goose: бинарь 7,6 → 13,7 МБ) — 6 017 670 байт. 25 МБ — в четыре раза больше
# нынешнего, но регрессию вроде образа на полном golang (сотни МБ) порог ловит.
max_bytes=25000000
# Срок на docker save: образ в несколько МБ выгружается за секунды, 5 минут — с запасом
# на холодный диск. Без срока зависший save повесил бы проверку навсегда.
save_timeout=300

fail() {
	echo "ПРОВАЛ: $image: $*" >&2
	exit 1
}

mb() { LC_ALL=C awk -v b="$1" 'BEGIN { printf "%.1f", b / 1e6 }'; }

# gzip -6 — тот же уровень, что у zlib по умолчанию в check-images.ts для вариантов.
size=$(timeout "$save_timeout" docker save "$image" | gzip -6 | wc -c) ||
	fail "docker save не завершился за $save_timeout с или упал"
[ "$size" -lt "$max_bytes" ] ||
	fail "сжатый размер $(mb "$size") МБ ($size байт), порог $(mb "$max_bytes") МБ"

user=$(docker image inspect -f '{{.Config.User}}' "$image")
[ "$user" = "65532:65532" ] || fail "пользователь «$user», ждали 65532:65532"

version=$(docker run --rm "$image" version)
[ "$version" = "$want_version" ] || fail "version ответил «$version», ждали «$want_version»"

echo "$image: сжатый размер $(mb "$size") МБ (порог $(mb "$max_bytes") МБ), пользователь $user, version $version"
