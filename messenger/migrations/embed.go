// Package migrations — SQL-миграции схемы мессенджера (goose), встроенные в бинарь.
// Применяет их подкоманда `messenger migrate up` отдельным шагом до старта сервера, а
// не сам сервер при старте: несколько экземпляров не гоняются за одной схемой, серверу
// не нужны права на DDL, а сбой миграции не превращается в цикл перезапусков (урок 2.8).
//
// Файлы после слияния в main не редактируются: изменение схемы — новая миграция со
// следующим номером. Применённую миграцию goose второй раз не выполнит, и правка в
// старом файле молча разошлась бы с базами, где он уже применён.
package migrations

import "embed"

// FS — файлы миграций: встроены в бинарь, поэтому образ distroless несёт схему с собой,
// и версия кода всегда совпадает с версией миграций, которые он умеет применить.
//
//go:embed *.sql
var FS embed.FS

// Required — последняя миграция, без которой бинарь не стартует: сервер сверяет с ней
// версию схемы в базе (goose_db_version). Поднимается, когда код начинает опираться на
// новую миграцию. База новее бинаря — допустимо: при выкладке миграции идут раньше
// кода, и старые экземпляры какое-то время работают с новой схемой (2b, expand/contract).
const Required int64 = 1
