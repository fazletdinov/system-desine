// Package pgtx — транзакции PostgreSQL, границу которых задаёт use case (ADR-0015).
//
// Use case объявляет у себя узкий порт Transactor с одним методом WithinTx и не знает
// про pgx. Transactor из этого пакета открывает транзакцию и кладёт её в ctx, а
// Postgres-адаптеры берут исполнителя запросов через Q(ctx, pool): транзакцию из ctx,
// если она есть, иначе пул. Так два адаптера разных контекстов (профиль в users и
// учётные данные в auth) пишут в одну транзакцию, не зная друг о друге.
//
// Цена — неявность: адаптер, который обратится к пулу напрямую, а не через Q, молча
// выполнит запрос вне транзакции. Защита — тест отката на каждую пишущую операцию
// адаптера.
//
// Вложенный WithinTx (ctx уже несёт транзакцию) не открывает новую и не ставит
// SAVEPOINT: fn выполняется во внешней транзакции, а фиксирует или откатывает её только
// внешний вызов. Почему без точек сохранения: вложенный вызов здесь — шаг той же
// бизнес-операции (адаптер, который сам оборачивает свои два запроса в WithinTx,
// вызван внутри транзакции use case'а), и операция удаётся или откатывается целиком.
// SAVEPOINT дал бы шагу «откатиться частично и продолжить» — но тогда ошибку шага
// можно проглотить, а внешний код об этом не узнает; и это лишние обращения к серверу
// на каждый шаг. Следствие: ошибку вложенного WithinTx нельзя проглатывать — после
// ошибки запроса Postgres отклоняет все команды транзакции до ROLLBACK (25P02).
//
// Транзакция pgx не для одновременного использования: fn не запускает горутины,
// которые работают с переданным ctx (а значит — с той же транзакцией). Пул в процессе
// один: Q и вложенный WithinTx не проверяют, что транзакция в ctx открыта тем же пулом.
