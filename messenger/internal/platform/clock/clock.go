package clock

import "time"

type System struct{}

// Now отдаёт UTC: часовой пояс — дело того, кто показывает время человеку.
//
// Время усечено до микросекунд — точности timestamptz в PostgreSQL. Иначе время в ответе
// и время, сохранённое в базе, расходились бы меньше чем на микросекунду: первый ответ на
// сообщение несёт sent_at с наносекундами, а повтор того же сообщения — уже прочитанный
// из базы, и клиент видел бы два разных sent_at у одного сообщения. Усечение здесь, а не в
// адаптере: домен и хранилище тогда работают с одним и тем же значением.
func (System) Now() time.Time { return time.Now().UTC().Truncate(time.Microsecond) }
