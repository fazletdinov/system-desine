// Package pgtest — настоящий PostgreSQL для интеграционных тестов адаптеров
// (testcontainers-go). Один контейнер на тестовый бинарь пакета: схема из
// messenger/migrations применяется один раз, база сохраняется снимком (Snapshot), и
// каждый тест начинает с чистой копии (Restore), а не с данными соседа. Так тест
// адаптера проверяет те же ограничения, индексы и транзакции, что в продакшене, —
// фейк в памяти их не повторит.
//
// Контейнер запускается при первом вызове Pool (2–6 с, первый раз на машине — ещё и
// загрузка образа), а не в Start: прогон, где отобраны только юнит-тесты пакета, Docker
// не трогает. Start в TestMain останавливает контейнер после всех тестов.
//
// Подключение в пакете с тестами:
//
//	func TestMain(m *testing.M) { os.Exit(pgtest.Start(m)) }
//
//	func TestSomething(t *testing.T) {
//		pool := pgtest.Pool(t) // чистая база со схемой; пул закроется после теста
//		…
//	}
//
// С -short (go test -short) тесты с Pool пропускаются, не трогая Docker: так идёт быстрая
// CI-джоба messenger-test. Без Docker тесты с Pool пропускаются с сообщением; MESSENGER_REQUIRE_DOCKER=1
// (CI-джоба messenger-integration) превращает пропуск в провал — иначе сломанный
// Docker на раннере выглядел бы зелёной сборкой без единого интеграционного теста.
//
// Здесь — один из двух разрешённых путей через database/sql (pgx/v5/stdlib): goose и
// снимки testcontainers принимают *sql.DB; тесты получают pgxpool, как и сервер.
