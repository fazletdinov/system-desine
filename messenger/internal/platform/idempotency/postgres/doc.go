// Package postgres — хранилище ключей идемпотентности в PostgreSQL (таблица
// platform.idempotency_keys): реализует idempotency.Store и idempotency.Sweeper и
// проходит тот же контракт storetest, что хранилище в памяти.
//
// Атомарность «проверить и занять» здесь держит не замок процесса, а сама база:
// INSERT … ON CONFLICT DO NOTHING занимает свободный ключ, UPDATE … WHERE с условием
// «просрочен или зависшая резервация» перехватывает занятый — из одновременных запросов
// строку получает ровно один, остальные ждут его фиксации и видят уже занятый ключ. Так
// ключ один на все экземпляры сервера, а не на процесс.
//
// Запросы идут через pgtx.Q, как у адаптеров контекстов: сегодня middleware зовёт
// хранилище вне транзакции операции (ADR-0005), но запись ключа в той же транзакции —
// следующий шаг, и адаптеру для него ничего менять не придётся.
