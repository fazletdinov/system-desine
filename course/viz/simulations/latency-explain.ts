// Термин подчёркивается один раз на объяснение: следующие вхождения идут обычным текстом.
function realText(item: LatencyItem, row: RowText, mode: LatencyMode): string {
  const parts = [`Модель Scott: ${latencyValue(item.model.ns, mode)}, экстраполяция трендов, а не замер.`, row.model]
  const r = item.range
  if (r) parts.push(`${r.estimate ? 'Оценка' : 'Реально'}: ${latencyRange(r, mode)} — ${r.source}${r.links ? ' (ссылки — под шкалой)' : ''}.`)
  if (item.id === 'ssd-random') parts.push(`У автора (fio, мимо кэша ОС): [[percentile|p50]] ${latencyValue(LAB_04.ssdRandP50.ns, mode)}, ${p99(LAB_04.ssdRandP99.ns)} — ${LAB_04.ssdRandP50.file}.`)
  else if (item.id === 'ssd-1mb') parts.push(`У автора: [[percentile|p50]] ${latencyValue(LAB_04.ssdSeqP50.ns, mode)}, ${p99(LAB_04.ssdSeqP99.ns)} — ${LAB_04.ssdSeqP50.file}.`)
  else if (item.author) parts.push(`У автора: ${latencyValue(item.author.ns, mode)} — ${item.author.file}.`)
  else parts.push('На машине автора этого не измерить.')
  return parts.join(' ')
}

const HERE_SCALE: Record<LatencyMode, string> = { real: 'В реальном времени', human: 'В человеческом масштабе (1 нс = 1 с)' }

function hereText(item: LatencyItem, view: LatencyView): Caption {
  const baseline = baselineOf(view.baselineId)
  const ratio = item.id === baseline.id ? 'Эта строка и есть точка отсчёта.' : `Это ${compare(item, baseline)}, чем «${captionText(baseline.label)}» (точка отсчёта).`
  return `${HERE_SCALE[view.mode]} — ${latencyValue(item.typical.ns, view.mode)} (${item.typical.source}). ${ratio}`
}

export function explainLatency(id: string, view: LatencyView): Explanation | null {
  const [kind, rowId] = id.split(':')
  if (kind !== 'row' || rowId === undefined) return null
  const item = LATENCIES.find((l) => l.id === rowId)
  const row = ROWS[rowId]
  if (item === undefined || row === undefined) return null
  const seen = new Set<string>()
  const text = (src: string): Caption => markedCaption(src, seen)
  return {
    title: captionText(item.label),
    kind: `${KIND_LABEL[item.kind]} · ${item.typical.source}`,
    sections: [
      { heading: 'Что это', body: text(row.what) },
      { heading: 'Почему столько', body: text(row.why) },
      { heading: 'В мессенджере', body: text(`${item.messenger[0]!.toUpperCase()}${item.messenger.slice(1)}. ${row.messenger}`) },
    ],
    here: hereText(item, view),
    real: text(realText(item, row, view.mode)),
  }
}

